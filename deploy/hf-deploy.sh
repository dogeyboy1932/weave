#!/usr/bin/env bash
# One-shot Hugging Face Space deploy (the free production host).
#
# The Space is a *deploy target*, not a mirror of the repo's git history:
# it carries a single flat snapshot commit. We push history-free because
#   (a) HF's pre-receive hook rejects the old binary blobs in samples/ that
#       still live in the repo's real history, and
#   (b) the Space only ever builds the current tree — history buys it nothing.
# Your GitHub `origin` keeps the full, real history; this script never touches it.
#
#   1. Verify you're on a clean tree (no uncommitted changes to snapshot).
#   2. Ensure the `space` git remote exists and points at HF over SSH.
#   3. Verify SSH auth to hf.co (key must be registered at
#      https://huggingface.co/settings/keys).
#   4. Build an orphan snapshot commit of the current tree and force-push it
#      as the Space's main.
#   5. Poll the Space build until RUNNING (or fail).
#   6. Smoke-test the live <title>.
#
# Usage:   deploy/hf-deploy.sh
# Config:  HF_SPACE=owner/space  (default: dogeyboy19/armchair)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

HF_SPACE="${HF_SPACE:-dogeyboy19/armchair}"
SPACE_SSH="git@hf.co:spaces/${HF_SPACE}"
BRANCH="${BRANCH:-main}"

# ── 1. Clean tree ────────────────────────────────────────────────────────────
# The snapshot is built from whatever's committed on $BRANCH, so refuse to
# deploy with uncommitted changes — otherwise "what shipped" is ambiguous.
if [[ -n "$(git status --porcelain)" ]]; then
  echo "Working tree has uncommitted changes. Commit or stash first." >&2
  git status --short >&2
  exit 1
fi
SRC_SHA="$(git rev-parse --short "$BRANCH")"
echo "==> Deploying $BRANCH @ $SRC_SHA to HF Space: $HF_SPACE"

# ── 2. Ensure the `space` remote points at HF over SSH ───────────────────────
if git remote get-url space >/dev/null 2>&1; then
  if [[ "$(git remote get-url space)" != "$SPACE_SSH" ]]; then
    echo "==> Repointing 'space' remote to $SPACE_SSH"
    git remote set-url space "$SPACE_SSH"
  fi
else
  echo "==> Adding 'space' remote: $SPACE_SSH"
  git remote add space "$SPACE_SSH"
fi

# ── 3. Verify SSH auth ───────────────────────────────────────────────────────
# hf.co greets you by username when your key is registered, "anonymous" if not.
echo "==> Checking SSH auth to hf.co…"
GREETING="$(ssh -T -o StrictHostKeyChecking=accept-new git@hf.co 2>&1 || true)"
if echo "$GREETING" | grep -qi "anonymous"; then
  cat >&2 <<EOF
SSH key not registered with Hugging Face (got: $GREETING).
Add your public key once at https://huggingface.co/settings/keys:
  cat ~/.ssh/id_rsa.pub    # or id_ed25519.pub
EOF
  exit 1
fi
echo "    $GREETING"

# ── 4. Snapshot + force-push ─────────────────────────────────────────────────
# Orphan branch carries the current tree with no parent, so the push contains
# exactly one commit and none of the historical binary blobs.
TMP="hf-deploy-$$"
cleanup() { git checkout -q "$BRANCH" 2>/dev/null || true; git branch -D "$TMP" >/dev/null 2>&1 || true; }
trap cleanup EXIT

git checkout -q --orphan "$TMP"
git commit -q -m "Deploy Weave to HF Space

Flat snapshot of $BRANCH @ $SRC_SHA. Full history lives on GitHub origin; the
Space carries a single snapshot commit to avoid HF's LFS/Xet rejection of
historical binary blobs. Generated by deploy/hf-deploy.sh."
echo "==> Force-pushing snapshot to $HF_SPACE (main)…"
git push --force space "${TMP}:main"

# ── 5. Poll build ────────────────────────────────────────────────────────────
echo "==> Waiting for the Space to rebuild (~1-2 min + cold start)…"
for i in $(seq 1 40); do
  STAGE="$(curl -s "https://huggingface.co/api/spaces/${HF_SPACE}" 2>/dev/null \
    | python3 -c "import sys,json;print(json.load(sys.stdin).get('runtime',{}).get('stage',''))" 2>/dev/null || true)"
  printf '\r    stage=%-24s' "$STAGE"
  case "$STAGE" in
    RUNNING) echo ""; break ;;
    BUILD_ERROR|RUNTIME_ERROR|*ERROR)
      echo ""
      echo "Build failed (stage=$STAGE). Check logs:" >&2
      echo "  https://huggingface.co/spaces/${HF_SPACE}?logs=build" >&2
      exit 1 ;;
  esac
  sleep 15
done

# ── 6. Smoke test ────────────────────────────────────────────────────────────
URL="https://$(echo "$HF_SPACE" | tr '/' '-').hf.space"
echo "==> Verifying live <title> at $URL…"
TITLE="$(curl -s "${URL}/?cachebust=$(date +%s)" 2>/dev/null | grep -io '<title>[^<]*</title>' | head -1 || true)"
echo ""
echo "════════════════════════════════════════════════════════════"
echo "  ✓ Weave deployed to HF Space: $HF_SPACE"
echo "    Live:  $URL"
echo "    Title: ${TITLE:-<not found — Space may still be cold-starting>}"
echo "════════════════════════════════════════════════════════════"
